import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import postcss from 'postcss'

// Check named CSS dependencies in every lazy entry, without borrowing CSS from
// sibling routes. This catches loading-order bugs; it is not a visual/layout test.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const absolute = name => path.join(root, name)
const relative = name => path.relative(root, name).replaceAll('\\', '/')
const sources = []
function walk(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) walk(file)
    else if (/\.(jsx?|tsx?|css)$/.test(file)) sources.push(file)
  }
}
walk(absolute('src'))

function resolve(from, specifier) {
  if (!specifier.startsWith('.')) return null
  const base = path.resolve(path.dirname(from), specifier)
  return [base, ...['.js', '.jsx', '.ts', '.tsx', '.css', '/index.js', '/index.jsx', '/index.ts', '/index.tsx'].map(ext => base + ext)]
    .find(file => fs.existsSync(file) && fs.statSync(file).isFile())
}

const modules = new Map()
const providers = new Map()
for (const file of sources) {
  const source = fs.readFileSync(file, 'utf8')
  const dependencies = [], lazy = [], classes = new Set()
  const addDependency = (specifier, target = dependencies) => {
    const dependency = resolve(file, specifier)
    if (dependency) target.push(dependency)
  }
  if (file.endsWith('.css')) {
    const css = postcss.parse(source, { from: file })
    css.walkRules(rule => {
      for (const [, name] of rule.selector.matchAll(/\.([A-Za-z_][\w-]*)/g)) {
        if (!providers.has(name)) providers.set(name, new Set())
        providers.get(name).add(file)
      }
    })
    css.walkAtRules('import', rule => {
      const specifier = rule.params.match(/['"]([^'"]+)/)?.[1]
      if (specifier) addDependency(specifier)
    })
  } else {
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, file.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS)
    function readClasses(node) {
      if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
        for (const name of node.text.split(/\s+/)) {
          // Ignore generic modifiers and utility classes whose definitions are
          // generated by Tailwind. Only check known, named application classes.
          if (/^[a-zA-Z][\w-]*-[\w-]+$/.test(name) && !/^(is|tone)-/.test(name)) classes.add(name)
        }
      } else ts.forEachChild(node, readClasses)
    }
    function visit(node) {
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) addDependency(node.moduleSpecifier.text)
      if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword && node.arguments[0] && ts.isStringLiteral(node.arguments[0])) addDependency(node.arguments[0].text, lazy)
      if (ts.isJsxAttribute(node) && node.name.text === 'className' && node.initializer) readClasses(node.initializer)
      ts.forEachChild(node, visit)
    }
    visit(ast)
  }
  modules.set(file, { dependencies, lazy, classes })
}

function closure(file, found = new Set()) {
  if (found.has(file)) return found
  found.add(file)
  for (const dependency of modules.get(file)?.dependencies || []) closure(dependency, found)
  return found
}
const startup = closure(absolute('src/main.jsx'))
const entries = new Set([...modules.values()].flatMap(module => module.lazy))
// These layouts surround nested <Outlet> routes in App.jsx. Their CSS is
// guaranteed on a direct visit, unlike CSS belonging to other lazy pages.
const routeLayouts = new Map([
  ['src/pages/captacion/CaptacionOverview.jsx', 'src/pages/captacion/CaptacionPage.jsx'],
  ['src/pages/MoreIntegrationsPage.jsx', 'src/pages/configuracion/ConfiguracionPage.jsx'],
  ['src/pages/AdministrationCenterPage.jsx', 'src/pages/configuracion/ConfiguracionPage.jsx'],
])
const failures = []
for (const entry of entries) {
  const available = new Set([...startup, ...closure(entry)])
  const layout = routeLayouts.get(relative(entry))
  if (layout) for (const dependency of closure(absolute(layout))) available.add(dependency)
  for (const file of available) {
    const missing = []
    for (const name of modules.get(file)?.classes || []) {
      const styles = providers.get(name)
      if (styles && ![...styles].some(style => available.has(style))) missing.push(name)
    }
    if (missing.length) failures.push(`${relative(entry)} -> ${relative(file)}: ${missing.join(', ')}`)
  }
}
if (failures.length) {
  console.error(`Missing CSS dependencies (${entries.size} lazy entries checked):\n${failures.join('\n')}`)
  process.exitCode = 1
} else {
  console.log(`CSS dependencies OK: ${entries.size} lazy entries, ${sources.length} source files checked.`)
}
